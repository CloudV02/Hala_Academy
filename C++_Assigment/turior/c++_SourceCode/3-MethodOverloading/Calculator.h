#ifndef CALCULATOR_H
#define CALCULATOR_H

class Calculator
{
	public:
		// Overloaded method to add two integers
		int add(int a, int b);

		// Overloaded method to add three integers
		int add(int a, int b, int c);

		// Method to add two floating-point numbers
		float add(float a, float b);
	};

#endif
